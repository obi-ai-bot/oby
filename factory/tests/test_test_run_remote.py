# `ssh ... true` exits with $FAKE/ssh-reach's code (0 without it). With $FAKE/no-user, a call with -l is refused as
# sshd refuses an unknown user. Any other command runs through sh in a session of its own, its standard input
# relayed and kept in $FAKE/stdin-<pid>; SIGUSR1 drops the connection (exit 255, the relay gone).
FAKE_SSH = """#!/usr/bin/env python3
import json, os, signal, subprocess, sys, threading
from pathlib import Path
fake = Path(os.environ["FAKE"])
argv = sys.argv[1:]
with open(fake / "ssh.log", "a") as log:
    log.write(json.dumps({"argv": argv, "pid": os.getpid()}) + "\\n")
if argv[-1] == "true":
    sys.exit(int((fake / "ssh-reach").read_text()) if (fake / "ssh-reach").exists() else 0)
if "-l" in argv and (fake / "no-user").exists():
    print(f"{argv[argv.index('-l') + 1]}@{argv[-2]}: Permission denied (publickey).", file=sys.stderr)
    sys.exit(255)
signal.signal(signal.SIGUSR1, lambda *_: os._exit(255))
remote = subprocess.Popen(["sh", "-c", argv[-1]], stdin=subprocess.PIPE, start_new_session=True)
def relay():
    with open(fake / f"stdin-{os.getpid()}", "ab") as kept:
        while True:
            chunk = os.read(0, 65536)
            if not chunk:
                break
            kept.write(chunk)
            kept.flush()
            remote.stdin.write(chunk)
            remote.stdin.flush()
    remote.stdin.close()
threading.Thread(target=relay, daemon=True).start()
sys.exit(remote.wait())
"""

# The VM's cargo: `fetch` is recorded; anything else records where and how it ran, with a child of its own, says
# so, waits while $FAKE/hold exists, and exits with $FAKE/cargo-exit's code.
VM_CARGO = """#!/usr/bin/env python3
import json, os, subprocess, sys, time
from pathlib import Path
fake = Path(os.environ["FAKE"])
if sys.argv[1] == "fetch":
    with open(fake / "vm-fetch", "a") as kept:
        kept.write(" ".join(sys.argv[1:]) + "\\n")
    sys.exit(0)
child = subprocess.Popen(["sleep", "300"])
names = ("CARGO_TARGET_DIR", "CARGO_NET_OFFLINE", "OBY_BUILD_JOBS", "CARGO_BUILD_JOBS", "RUST_TEST_THREADS",
         "NEXTEST_TEST_THREADS")
record = {"args": sys.argv[1:], "cwd": os.getcwd(), "nice": os.getpriority(os.PRIO_PROCESS, 0), "pid": os.getpid(),
          "child": child.pid, **{name: os.environ.get(name) for name in names}}
with open(fake / "vm-runs", "a") as kept:
    kept.write(json.dumps(record) + "\\n")
print("the VM's cargo ran", flush=True)
while (fake / "hold").exists():
    time.sleep(0.05)
child.kill()
sys.exit(int((fake / "cargo-exit").read_text()) if (fake / "cargo-exit").exists() else 0)
"""

# This Mac's cargo and swift: each records its words and the lock's holder line, and says so.
MAC_TOOL = """#!/bin/sh
echo "$(basename "$0") $* | $(cat "$OBY_TEST_RUN_LOCK")" >>"$FAKE/mac-runs"
echo "this Mac's $(basename "$0") ran"
"""

# The stand-in check: its plan names no group, so a gate in gate mode takes a slot and ends 0.
FAKE_CHECK = "#!/bin/sh\nexit 0\n"

TINY = {
    "core/Cargo.toml": '[package]\nname = "tiny"\nversion = "0.1.0"\nedition = "2021"\n',
    "core/Cargo.lock": '# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "tiny"\n'
                       'version = "0.1.0"\n',
    "core/src/lib.rs": "#[cfg(test)]\nmod tests {\n    #[test]\n    fn a_test() {}\n}\n",
}
B_LIB = "#[cfg(test)]\nmod tests {\n    #[test]\n    fn a_test() {}\n\n    #[test]\n    fn b_only() {}\n}\n"


def gone(pid, seconds=15):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return True
        time.sleep(0.05)
    return False


class RemoteHarness:
    """The throwaway repository, fake hosts and helpers, for a unittest.TestCase that mixes it in: this file's and
    test_test_run_mac_worker.py's, which imports it without running these tests again."""

    def setUp(self):
        self.dir = Path(tempfile.mkdtemp()).resolve()
        self.fake = self.dir / "fake"
        self.fake.mkdir()
        self.bin = self.dir / "bin"
        self.bin.mkdir()
        for name, text in (("az", FAKE_AZ), ("ssh", FAKE_SSH), ("cargo", MAC_TOOL), ("swift", MAC_TOOL)):
            self.tool(self.bin / name, text)
        (self.bin / "oby-remote-gate").symlink_to(OBY_REMOTE_GATE)
        self.home = self.dir / "home"
        self.tool(self.home / ".cargo" / "bin" / "cargo", VM_CARGO)
        self.lock = self.dir / "test-run.lock"
        self.env = {k: v for k, v in os.environ.items()
                    if not k.startswith(("OBY_", "FACTORY_", "CARGO_", "npm_config_")) and k not in CORE_VARS}
        self.env.update(
            GIT_CONFIG_GLOBAL="/dev/null", GIT_CONFIG_NOSYSTEM="1",
            GIT_AUTHOR_NAME="test", GIT_AUTHOR_EMAIL="test@example.com",
            GIT_COMMITTER_NAME="test", GIT_COMMITTER_EMAIL="test@example.com",
            HOME=str(self.home), FAKE=str(self.fake), PATH=f"{self.bin}{os.pathsep}{os.environ['PATH']}",
            OBY_TEST_RUN_LOCK=str(self.lock), CARGO_TARGET_DIR_FACTORY=str(self.dir / "shared-target"),
            FACTORY_REMOTE_IP_URL=(self.fake / "ip").as_uri(),
        )
        self.settings(builder_slots=2)
        (self.fake / "states").write_text("PowerState/running\n")
        (self.fake / "rule-source").write_text(f"{IP}/32\n")
        (self.fake / "ip").write_text(f"{IP}\n")
        # origin's dev: the factory's scripts and settings, a tiny crate and some of obid's files.
        self.origin = self.dir / "origin.git"
        seed = self.dir / "seed"
        self.git(self.dir, "init", "-q", "--bare", str(self.origin))
        self.git(self.origin, "config", "uploadpack.allowAnySHA1InWant", "true")
        self.git(self.dir, "init", "-q", "-b", "dev", str(seed))
        for name in ("gate", "test-run", "child_session.py"):
            self.put(seed / "factory" / "bin" / name, (FACTORY / "bin" / name).read_text(), 0o755)
        self.put(seed / "factory" / "config.json", (FACTORY / "config.json").read_text())
        self.put(seed / ".gitleaks.toml", (REPO / ".gitleaks.toml").read_text())
        self.put(seed / ".gitignore", "ignored/\n")
        self.put(seed / "scripts" / "oby-check.sh", FAKE_CHECK, 0o755)
        for path, text in TINY.items():
            self.put(seed / path, text)
        for path in ("core/crates/obid/src/gateway.rs", "core/crates/obid/src/sandbox.rs",
                     "core/crates/obid/tests/one.rs", "core/crates/obid/tests/sandbox.rs"):
            self.put(seed / path, "// obid\n")
        self.git(seed, "add", ".")
        self.git(seed, "commit", "-q", "-m", "base")
        self.git(seed, "push", "-q", str(self.origin), "dev")
        self.base = self.git(seed, "rev-parse", "HEAD")
        # The main checkout and the job's worktree, added from it.
        self.main = self.dir / "main"
        self.git(self.dir, "clone", "-q", "-b", "dev", str(self.origin), str(self.main))
        self.worktree = self.add_worktree("x")
        self.state = self.main / "factory" / "jobs" / "remote-gate" / "state.json"
        # The VM's builder root, as setup.sh makes /srv/oby-builder.
        self.root = self.dir / "vm"
        self.root.mkdir()
        self.git(self.dir, "clone", "-q", "--bare", str(self.origin), str(self.root / "repo.git"))
        self.env.update(OBY_REMOTE_ROOT=str(self.root), OBY_REMOTE_URL=str(self.origin))
        self.started = []
        self.held = []

    def tearDown(self):
        (self.fake / "hold").unlink(missing_ok=True)
        for proc in self.started:
            if proc.poll() is None:
                proc.kill()
                proc.wait()
            proc.stdout.close()
            proc.stderr.close()
        for fd in self.held:
            os.close(fd)
        for run in self.vm_runs():
            for pid in (run["pid"], run["child"]):
                try:
                    os.kill(pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
        shutil.rmtree(self.dir)

    def tool(self, path, text):
        self.put(path, text, 0o755)

    def put(self, path, text, mode=None):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        if mode:
            path.chmod(mode)

    def git(self, cwd, *args):
        return subprocess.run(["git", *args], cwd=cwd, env=self.env, check=True,
                              capture_output=True, text=True).stdout.strip()

    def add_worktree(self, name):
        path = self.dir / f"worktree-{name}"
        self.git(self.main, "worktree", "add", "-q", "-b", f"factory/{name}", str(path), "origin/dev")
        return path

    def settings(self, **keys):
        self.env["FACTORY_REMOTE_GATE"] = json.dumps({**KEYS, **keys})

    def start(self, *command, worktree=None, **env):
        worktree = worktree or self.worktree
        proc = subprocess.Popen(
            [str(worktree / "factory" / "bin" / "test-run"), "--", *command], cwd=worktree / "core",
            env={**self.env, "CARGO_TARGET_DIR": str(worktree / "core" / "target"), **env},
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        self.started.append(proc)
        return proc

    def run_test_run(self, *command, **kw):
        proc = self.start(*command, **kw)
        out, err = proc.communicate(timeout=120)
        return proc.returncode, out, err, proc.pid

    def lines(self, name):
        path = self.fake / name
        return path.read_text().splitlines() if path.exists() else []

    def ssh_calls(self):
        return [json.loads(line) for line in self.lines("ssh.log")]

    def run_calls(self):
        return [call for call in self.ssh_calls() if "--run" in shlex.split(call["argv"][-1])]

    def stdin(self, call):
        path = self.fake / f"stdin-{call['pid']}"
        return path.read_bytes() if path.exists() else b""

    def vm_runs(self):
        return [json.loads(line) for line in self.lines("vm-runs")]

    def wait_for_vm_runs(self, count, seconds=60):
        deadline = time.monotonic() + seconds
        while len(self.vm_runs()) < count and time.monotonic() < deadline:
            time.sleep(0.05)
        self.assertEqual(len(self.vm_runs()), count, self.vm_runs())

    def hold_slot(self, name):
        (self.root / name).mkdir(exist_ok=True)
        fd = os.open(self.root / name / "lock", os.O_RDWR | os.O_CREAT, 0o644)
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        self.held.append(fd)

    def assert_slot_free(self, name):
        fd = os.open(self.root / name / "lock", os.O_RDWR)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        finally:
            os.close(fd)

    def write(self, path, text, worktree=None):
        self.put((worktree or self.worktree) / path, text)

    def assert_on_this_mac(self, result, line, tool="cargo", tried=0):
        """The run went to this Mac's tool, under the lock, saying so in one line, and never ran on the VM (tried:
        how many ssh calls carried --run before it fell back)."""
        code, out, err, pid = result
        self.assertEqual(code, 0, out + err)
        self.assertIn(f"this Mac's {tool} ran", out)
        [run] = self.lines("mac-runs")
        self.assertTrue(run.split(" | ", 1)[1].startswith(f"{pid} "), f"{run}: not under the lock")
        said = [x for x in err.splitlines() if x.startswith("factory/bin/test-run: ") and " this Mac: " in x]
        self.assertEqual(said, [f"factory/bin/test-run: {line}"], err)
        self.assertEqual(len(self.run_calls()), tried)
        self.assertEqual(self.vm_runs(), [])


