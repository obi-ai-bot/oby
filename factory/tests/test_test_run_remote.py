    def test_remote_23_two_builders_run_at_once_and_a_gate_still_gets_a_slot(self):
        (self.fake / "hold").touch()
        a = self.start("cargo", "test", "--test", "one")
        b = self.start("cargo", "test", "--test", "one", worktree=self.add_worktree("y"))
        self.wait_for_vm_runs(2)
        targets = sorted(run["CARGO_TARGET_DIR"] for run in self.vm_runs())
        self.assertEqual(targets, [str(self.root / f"builder-{n}" / "target") for n in (1, 2)])
        # Every builder slot is held: a gate takes a gate slot at once.
        started = time.monotonic()
        gate = subprocess.Popen([str(OBY_REMOTE_GATE), self.base, "origin/dev"], env=self.env,
                                stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        out = gate.stdout.read()
        self.assertEqual(gate.wait(timeout=30), 0, out)
        gate.stdin.close()
        gate.stdout.close()
        self.assertIn("oby-remote-gate: slot 1\n", out)
        self.assertNotIn("busy", out)
        self.assertLess(time.monotonic() - started, 30)
        (self.fake / "hold").unlink()
        for proc in (a, b):
            out, err = proc.communicate(timeout=60)
            self.assertEqual(proc.returncode, 0, out + err)

