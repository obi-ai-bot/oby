#!/usr/bin/env python3
"""factory/bin/test-run's builder path to the gate VM (REMOTE-22 to 29 and 31), with a fake `az` and `ssh`, never
the VM or the network.

Run from the repository root: python3 factory/tests/test_test_run_remote.py
Each test builds a throwaway repository: a bare `origin` whose `dev` holds copies of factory/bin's gate, test-run
and child_session.py, the real factory/config.json and .gitleaks.toml, a tiny real Cargo crate in core/ and a few
of obid's file names; a main checkout cloned from it; and a job's worktree added from that main checkout, whose
copy of test-run is the one run. The fake `ssh` comes first on PATH: it records its arguments and what it is
given on standard input, answers `true` from a file the test writes, and runs any other command with the real
factory/remote/oby-remote-gate in a session of its own, as the VM's sshd would, with OBY_REMOTE_ROOT and
OBY_REMOTE_URL pointing it at a local root and origin. The VM's cargo is a stand-in in the fake home's
~/.cargo/bin (the real one for REMOTE-27); this Mac's cargo and swift are stand-ins first on PATH.
"""

